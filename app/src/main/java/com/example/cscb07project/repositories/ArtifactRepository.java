package com.example.cscb07project.repositories;

import com.example.cscb07project.entities.Artifact;
import com.example.cscb07project.entities.ExpandedView;
import com.example.cscb07project.entities.User;
import com.google.android.gms.tasks.Task;
import com.google.firebase.database.DataSnapshot;
import com.google.firebase.database.DatabaseReference;
import com.google.firebase.database.FirebaseDatabase;

public class ArtifactRepository {
    private final DatabaseReference dbRef;
    private final ExpandedViewRepository expandedViewRepository;

    public ArtifactRepository(FirebaseDatabase rootRef, ExpandedViewRepository expandedViewRepository) { // expected to use rootRef for expandedView
        this.dbRef = rootRef.getReference("artifacts");
        this.expandedViewRepository = expandedViewRepository;
    }

    // add user
    public void addArtifact(Artifact artifact) {
        // assume it contains all keys as identified in the class
        String lotNumber = dbRef.push().getKey(); // fetch autogenerated ID after every post
        if (lotNumber == null) throw new IllegalStateException();
        artifact.setLotNumber(lotNumber);
        dbRef.child(lotNumber).setValue(artifact);

        // also call ExpandedView
        expandedViewRepository.addExpandedView(artifact.getLotNumber(), new ExpandedView(artifact.getLotNumber(), 0));
    }

    public Task<DataSnapshot> getArtifactByLotNumber(String lotNumber) {
        return dbRef.child(lotNumber).get();
    }
}
